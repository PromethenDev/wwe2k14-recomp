#!/usr/bin/env python3
"""Generate the synthetic launcher test fixtures under out/l1/testdata for WWE 2K14.

The launcher core tests (core_test, disc_image_test, packages_test) read small game-shaped fixtures:
a title-id-545408B2 XEX, a matching 1.0.3 delta patch, and read-only STFS title-update / DLC packages.
None of this is real game data - it is generated byte patterns that exercise the readers.

Usage: python3 launcher2/core/tests/make_testdata.py [OUTPUT_DIR]
Defaults to <repo>/out/l1/testdata. Never touches retail files.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

TITLE_ID = 0x545408B2
BLOCK = 0x1000
BLOCKS_PER_HASH_TABLE = 0xAA
EOC = 0xFFFFFF
DISPLAY_NAME_OFFSET = 0x411
VOLUME_DESCRIPTOR_OFFSET = 0x379
HEADER_SIZE = 0x1000
CONTENT_TYPE_TITLE_UPDATE = 0x000B0000
CONTENT_TYPE_DLC = 0x00000002

XEX2_MAGIC = 0x58455832
EXECUTION_INFO_KEY = 0x00040006
DELTA_PATCH_KEY = 0x000005FF
TU_TARGET_VERSION = 0x00000102
SOURCE_VERSION = 0x00000002


def be32(value: int) -> bytes:
    return struct.pack(">I", value)


def make_xex(title_id: int = TITLE_ID, version: int = SOURCE_VERSION) -> bytes:
    data = bytearray(HEADER_SIZE)
    struct.pack_into(">I", data, 0, XEX2_MAGIC)
    struct.pack_into(">I", data, 8, HEADER_SIZE)
    struct.pack_into(">I", data, 0x14, 1)  # optional header count
    struct.pack_into(">II", data, 0x18, EXECUTION_INFO_KEY, 0x200)
    struct.pack_into(">III", data, 0x200 + 4, version, version, title_id)
    return bytes(data)


def make_xexp(target: int = TU_TARGET_VERSION, source: int = SOURCE_VERSION) -> bytes:
    data = bytearray(HEADER_SIZE)
    struct.pack_into(">I", data, 0, XEX2_MAGIC)
    struct.pack_into(">I", data, 8, HEADER_SIZE)
    struct.pack_into(">I", data, 0x14, 1)
    struct.pack_into(">II", data, 0x18, DELTA_PATCH_KEY, 0x200)
    struct.pack_into(">III", data, 0x200, 0x4C, target, source)  # descriptor size, target, source
    return bytes(data)


def pattern(seed: int, size: int) -> bytes:
    return bytes(((seed * 31 + i * 7) & 0xFF) for i in range(size))


def _utf16be(text: str) -> bytes:
    return text.encode("utf-16-be") + b"\x00\x00"


def build_read_only_stfs(content_type: int, display_name: str, files: list[tuple[str, bytes]]) -> bytes:
    """One read-only STFS package holding `files` (relative POSIX paths -> bytes)."""
    # Directories first, then files, so parent indices are easy to resolve.
    directories: list[str] = []
    for name, _ in files:
        parent = str(Path(name).parent)
        while parent not in ("", "."):
            if parent not in directories:
                directories.append(parent)
            parent = str(Path(parent).parent)
    directories.sort()

    entries: list[tuple[str, bool, int, int, int, int]] = []  # name, is_dir, block, block_count, size, parent
    dir_index: dict[str, int] = {}
    for directory in directories:
        parent = str(Path(directory).parent)
        entries.append((Path(directory).name, True, 0, 0, 0,
                        0xFFFF if parent in ("", ".") else dir_index[parent]))
        dir_index[directory] = len(entries) - 1

    file_blocks: list[tuple[int, int, int]] = []  # first_block, block_count, size
    next_block = 1  # logical block 0 is the file table
    file_data: list[bytes] = []
    for name, contents in files:
        parent = str(Path(name).parent)
        blocks = (len(contents) + BLOCK - 1) // BLOCK or 1
        entries.append((Path(name).name, False, next_block, blocks, len(contents),
                        0xFFFF if parent in ("", ".") else dir_index[parent]))
        file_blocks.append((next_block, blocks, len(contents)))
        file_data.append(contents)
        next_block += blocks

    total_blocks = next_block

    header = bytearray(HEADER_SIZE)
    header[0:4] = b"CON "
    struct.pack_into(">I", header, 0x340, HEADER_SIZE)
    struct.pack_into(">I", header, 0x344, content_type)
    struct.pack_into(">I", header, 0x360, TITLE_ID)
    struct.pack_into(">I", header, 0x3A9, 0)  # volume type 0
    descriptor = bytearray(0x20)
    descriptor[0] = 0x24
    descriptor[2] = 0x01  # read-only
    struct.pack_into("<H", descriptor, 3, 1)  # file table block count
    descriptor[5:8] = (0).to_bytes(3, "little")  # file table first block
    struct.pack_into(">I", descriptor, 0x1C, total_blocks)
    header[VOLUME_DESCRIPTOR_OFFSET:VOLUME_DESCRIPTOR_OFFSET + len(descriptor)] = descriptor
    name_bytes = _utf16be(display_name)
    assert len(name_bytes) <= 0x80, "STFS display name too long"
    header[DISPLAY_NAME_OFFSET:DISPLAY_NAME_OFFSET + len(name_bytes)] = name_bytes

    # File table block (logical 0 -> physical 1).
    table = bytearray(BLOCK)
    for index, (name, is_dir, block, block_count, size, parent) in enumerate(entries):
        raw = bytearray(0x40)
        name_bytes_file = name.encode("latin-1")
        assert len(name_bytes_file) <= 0x28
        raw[0:len(name_bytes_file)] = name_bytes_file
        raw[0x28] = len(name_bytes_file) | (0x80 if is_dir else 0)
        raw[0x2C:0x2F] = block_count.to_bytes(3, "little")
        raw[0x2F:0x32] = block.to_bytes(3, "little")
        struct.pack_into(">H", raw, 0x32, parent)
        struct.pack_into(">I", raw, 0x34, size)
        table[index * 0x40:(index + 1) * 0x40] = raw

    # Hash table (physical 0) chain pointers for the file table and every data block.
    hash_table = bytearray(BLOCK)
    chains: dict[int, int] = {0: EOC}
    for first, blocks, _size in file_blocks:
        for offset in range(blocks):
            chains[first + offset] = EOC if offset == blocks - 1 else first + offset + 1
    for block, next_value in chains.items():
        struct.pack_into(">I", hash_table, (block % BLOCKS_PER_HASH_TABLE) * 0x18 + 0x14, next_value)

    package = bytearray(header)
    package += hash_table
    package += table
    for contents in file_data:
        padded = contents + b"\x00" * (((len(contents) + BLOCK - 1) // BLOCK or 1) * BLOCK - len(contents))
        package += padded
    return bytes(package)


def make_content_header(display_name: str, package_name: str) -> bytes:
    header = bytearray(0x14C)
    struct.pack_into(">I", header, 0, 1)  # HDD device id
    struct.pack_into(">I", header, 4, 2)  # marketplace content
    name = _utf16be(display_name)
    header[8:8 + len(name)] = name
    pkg = package_name.encode("utf-8")
    header[0x108:0x108 + len(pkg)] = pkg
    struct.pack_into(">Q", header, 0x138, 0)
    struct.pack_into(">I", header, 0x140, TITLE_ID)
    header[0x148:0x14C] = b"\xFF\xFF\xFF\xFF"
    return bytes(header)


def write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


def main() -> int:
    repo = Path(__file__).resolve().parents[3]
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else repo / "out" / "l1" / "testdata"
    output.mkdir(parents=True, exist_ok=True)

    xex = make_xex()
    xexp = make_xexp()
    plist = pattern(1, 0x180)
    plist_4x3 = pattern(2, 0x180)

    for folder in ("tu-folder-min", "base-only-min"):
        write(output / folder / "default.xex", xex)
    write(output / "tu-folder-min" / "default.xexp", xexp)
    write(output / "tu-folder-min" / "plist360.def", plist)
    write(output / "tu-folder-min" / "plist360_4x3.def", plist_4x3)

    # Title update: a read-only STFS package with the same files the game folder holds.
    tu_name = "TU_1A5225K_0000008000000.0000000000082"
    tu_files = [
        ("default.xexp", xexp),
        ("plist360.def", plist),
        ("plist360_4x3.def", plist_4x3),
        ("pac/DLC.pac", pattern(9, 0x1000)),
    ]
    tu_package = build_read_only_stfs(CONTENT_TYPE_TITLE_UPDATE, "WWE 2K14 Title Update", tu_files)
    write(output / "packages" / "TU_1A5225K_0000008000000" / tu_name, tu_package)

    # DLC: read-only STFS packages plus the extracted trees and headers ImportDlc would produce.
    dlc_cases = [
        ("WWE 2K14 - DLC Pack 2 (World) (Addon)", "9FAF6BD4EADAD29A4AA3517843077FC877DDFA0WWE", "WWE 2K14 Pack 2"),
        ("WWE 2K14 - DLC Pack 3 (World) (Addon)", "AE201CFDEFFB0C988B4A1DC89EDF2B4F7491FB5354", "WWE 2K14 Pack 3"),
        ("WWE 2K14 - Pack 1 (World) (DLC)", "B64239E5B81FC5EFE8CEF7E695F77223A9D39A0F54", "WWE 2K14 Pack 1"),
    ]
    dlc_contents = [
        [("info/catalog.dlc", pattern(20, 0x120)), ("content.bin", pattern(21, 0x900))],
        [("data.pac", pattern(30, 0x800))],
        [("info/catalog.dlc", pattern(40, 0x100)), ("readme.txt", b"WWE 2K14 test pack\n")],
    ]
    expected_root = output / "expected-dlc-content" / "545408B2"
    for (folder_name, package_name, display_name), files in zip(dlc_cases, dlc_contents):
        source_dir = output / "packages" / folder_name / "545408B2" / "00000002"
        write(source_dir / package_name,
              build_read_only_stfs(CONTENT_TYPE_DLC, display_name, files))
        for relative, contents in files:
            write(expected_root / "00000002" / package_name / relative, contents)
        write(expected_root / "Headers" / "00000002" / (package_name + ".header"),
              make_content_header(display_name, package_name))

    count = sum(1 for path in output.rglob("*") if path.is_file())
    print(f"Wrote {count} fixture files under {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
