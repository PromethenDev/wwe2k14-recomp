#!/usr/bin/env python3
"""Embed the home-screen tile icon PNGs into a header in the build directory."""

import pathlib
import sys

NAMES = ("play", "creation_suite", "settings", "controls", "saves", "game_files", "mods")


def main() -> int:
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_images.py IMAGE_DIR OUTPUT_HEADER")
    image_dir = pathlib.Path(sys.argv[1])
    output = pathlib.Path(sys.argv[2])
    lines = ["// Generated by ui/generate_images.py - do not edit.", "#pragma once", "#include <cstddef>", ""]
    for name in NAMES:
        data = (image_dir / f"tile_{name}.png").read_bytes()
        body = ",".join(str(b) for b in data)
        lines.append(f"inline constexpr unsigned char kTileImage_{name}[] = {{{body}}};")
    lines.append("")
    lines.append("struct EmbeddedTileImage { const unsigned char* data; size_t size; };")
    lines.append("inline constexpr EmbeddedTileImage kTileImages[] = {")
    for name in NAMES:
        lines.append(f"  {{kTileImage_{name}, sizeof(kTileImage_{name})}},")
    lines.append("};")
    output.write_text("\n".join(lines) + "\n", encoding="ascii")
    return 0


if __name__ == "__main__":
    sys.exit(main())
