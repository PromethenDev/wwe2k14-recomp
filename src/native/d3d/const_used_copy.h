inline constexpr uint32_t kRegisterCount = 256;
inline constexpr uint32_t kWords = kRegisterCount / 64;
inline constexpr uint32_t kRegisterBytes = 16;
inline constexpr uint32_t kBlockBytes = kRegisterCount * kRegisterBytes;
inline constexpr uint64_t kAllBits = UINT64_MAX;

struct CopyResult {
  uint32_t copied_registers = 0;
  uint32_t cleared_registers = 0;
  bool full_copy = false;
};

struct CoverageResult {
  int32_t first_missing_register = -1;
  uint32_t copied_registers = 0;
};

inline bool HasRow(const uint64_t rows[kWords], uint32_t row) {
  return (rows[row / 64] & (uint64_t(1) << (row % 64))) != 0;
}

// ConstantRegisterMap::float_dynamic_addressing is set for non-absolute float operands (including
// a0- and aL-relative accesses); the SDK expands such maps to all 256 in-block rows. Keep that
// conservative contract here so a future sparse mask cannot omit any row reachable by either mode.
// This checks in-block row coverage; GPU-assisted validation is still needed for an address that
// underflows or overflows the constant buffer itself.
inline CoverageResult CheckReadCoverage(const uint64_t* static_usage, bool dynamic_addressing,
                                       const uint64_t copied[kWords]) {
  CoverageResult result;
  for (uint32_t row = 0; row < kRegisterCount; ++row) {
    const bool is_copied = HasRow(copied, row);
    if (is_copied) ++result.copied_registers;
    const bool is_read = dynamic_addressing || !static_usage || HasRow(static_usage, row);
    if (is_read && !is_copied && result.first_missing_register < 0)
      result.first_missing_register = int32_t(row);
  }
  return result;
}

inline std::string DescribeRows(const uint64_t rows[kWords]) {
  std::string result;
  uint32_t first = kRegisterCount;
  for (uint32_t row = 0; row <= kRegisterCount; ++row) {
    const bool present = row < kRegisterCount && HasRow(rows, row);
    if (present && first == kRegisterCount) first = row;
    if (!present && first != kRegisterCount) {
      if (!result.empty()) result += ',';
      result += 'c' + std::to_string(first);
      if (first != row - 1) result += "-c" + std::to_string(row - 1);
      first = kRegisterCount;
    }
  }
  return result.empty() ? "none" : result;
}

inline void SetAll(uint64_t mask[kWords]) {
  for (uint32_t i = 0; i < kWords; ++i) mask[i] = kAllBits;
}

inline bool IsAll(const uint64_t mask[kWords]) {
  for (uint32_t i = 0; i < kWords; ++i)
    if (mask[i] != kAllBits) return false;
  return true;
}

