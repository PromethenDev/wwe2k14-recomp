template <std::size_t N>
inline bool ContainsKey(const uint64_t (&keys)[N], uint64_t key) {
  std::size_t lo = 0, hi = N;
  while (lo < hi) {
    const std::size_t mid = lo + (hi - lo) / 2;
    if (keys[mid] < key) lo = mid + 1;
    else hi = mid;
  }
  return lo < N && keys[lo] == key;
}

inline bool HasVerifiedMap(ShaderStage stage, uint64_t key) {
  return stage == ShaderStage::kVertex ? ContainsKey(kVerifiedVertexShaderKeys, key)
                                       : ContainsKey(kVerifiedPixelShaderKeys, key);
}

// Returns true only when the source bitmap belongs to an offline-verified shader key. Dynamic addressing,
// an unknown key, a missing map, or a substituted shader always receives all rows.
inline bool SelectSafeUsage(ShaderStage stage, uint64_t key, const uint64_t* usage, bool dynamic,
                            bool force_full, uint64_t out[kWords]) {
  if (!usage || dynamic || force_full || !HasVerifiedMap(stage, key)) {
    SetAll(out);
    return false;
  }
  std::memcpy(out, usage, sizeof(uint64_t) * kWords);
  return true;
}

// GUARD=0 preserves V17e's original unguarded selection: use the SDK map verbatim, or all rows if no map exists.
// GUARD=1 applies V17g's exact-key whitelist and full-copy fallbacks.
inline bool SelectCopyUsage(ShaderStage stage, uint64_t key, const uint64_t* usage, bool dynamic,
                            bool force_full, bool guard, uint64_t out[kWords]) {
  if (guard) return SelectSafeUsage(stage, key, usage, dynamic, force_full, out);
  if (!usage) {
    SetAll(out);
    return false;
  }
  std::memcpy(out, usage, sizeof(uint64_t) * kWords);
  return true;
}


// `retained` describes the rows currently present in `dst`. Unused rows are always zero. A null map and a
// dynamically indexed shader are both represented by all bits set and take the exact full-block fallback.
inline CopyResult Copy(uint8_t* dst, uint64_t retained[kWords], const uint8_t* src,
                       const uint64_t* usage, bool sparse, bool pad_zero = false) {
  if (!sparse || !usage) {
    std::memcpy(dst, src, kBlockBytes);
    SetAll(retained);
    return {kRegisterCount, 0, true};
  }

  uint64_t current[kWords];
  std::memcpy(current, usage, sizeof(current));
  if (IsAll(current)) {
    std::memcpy(dst, src, kBlockBytes);
    std::memcpy(retained, current, sizeof(current));
    return {kRegisterCount, 0, true};
  }

  CopyResult result;
  if (pad_zero) std::memset(dst, 0, kBlockBytes);
  for (uint32_t word = 0; word < kWords; ++word) {
    uint64_t clear = retained[word] & ~current[word];
    while (clear) {
      const uint32_t bit = std::countr_zero(clear);
      std::memset(dst + (word * 64 + bit) * kRegisterBytes, 0, kRegisterBytes);
      clear &= clear - 1;
      ++result.cleared_registers;
    }

    uint64_t copy = current[word];
    while (copy) {
      const uint32_t bit = std::countr_zero(copy);
      std::memcpy(dst + (word * 64 + bit) * kRegisterBytes,
                  src + (word * 64 + bit) * kRegisterBytes, kRegisterBytes);
      copy &= copy - 1;
      ++result.copied_registers;
    }
    retained[word] = current[word];
  }
  return result;
}

inline uint32_t DifferenceCount(const uint8_t* a, const uint8_t* b, const uint64_t usage[kWords]) {
  uint32_t different = 0;
  for (uint32_t word = 0; word < kWords; ++word) {
    uint64_t bits = usage[word];
    while (bits) {
      const uint32_t bit = std::countr_zero(bits);
      const size_t offset = size_t(word * 64 + bit) * kRegisterBytes;
      different += std::memcmp(a + offset, b + offset, kRegisterBytes) != 0;
      bits &= bits - 1;
    }
  }
  return different;
}

inline bool UsedRowsEqual(const uint8_t* a, const uint8_t* b, const uint64_t usage[kWords]) {
  return DifferenceCount(a, b, usage) == 0;
}

